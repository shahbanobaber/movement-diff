"""Which alignment recovers a known change best? Writes validation/alignment_benchmark.md.

Two synthetic scenarios (see movediff/synth.py), six seeds each, four ways of
putting reps on a shared timeline. For each, the wrist shift curve the tool
reports is compared with the shift that was injected.

Run from the repo root:  python validation/benchmark_alignment.py
Takes a few minutes on a laptop CPU. No network, no paid APIs.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from movediff.align import Aligner, resample  # noqa: E402
from movediff.metrics import build_conditions, compare, phase_masks  # noqa: E402
from movediff.segment import segment  # noqa: E402
from movediff.synth import HAND, REST, TARGET, TRUTH, UNDERSHOOT, _elbow, _min_jerk, write_sessions  # noqa: E402

MODES = ("none", "position", "velocity-refined", "velocity", "speed")
LABELS = {
    "none": "none (linear 0-100% time only)",
    "position": "DTW on joint position",
    "velocity-refined": "DTW on joint velocity, target = mean of warped baseline",
    "velocity": "DTW on joint velocity, target = medoid rep (default)",
    "speed": "DTW on joint speed",
}
SEEDS = (10, 20, 30, 40, 50, 60)
L = 101


def truth_curves() -> dict[str, np.ndarray]:
    # Reps are cut where speed crosses 10% of peak, which for a minimum-jerk
    # reach is 8.6% and 91.4% of its full duration.
    tau = 0.086 + 0.828 * np.linspace(0, 1, L)
    k = np.arange(20)
    amp = (TRUTH["bulge_mean_test"] + TRUTH["bulge_extra_first"] * np.exp(-k / TRUTH["bulge_decay_reps"])).mean()
    return {
        "bulge": amp * np.exp(-0.5 * ((tau - TRUTH["bulge_centre"]) / TRUTH["bulge_width"]) ** 2),
        "undershoot": UNDERSHOOT * _min_jerk(tau),
    }


def arm_reach(time_power: float = 1.0, n: int = 80) -> np.ndarray:
    """Clean elbow/wrist/index reach whose clock runs as t**time_power."""
    tau = np.linspace(0, 1, n) ** time_power
    w = REST + _min_jerk(tau)[:, None] * (TARGET - REST)
    w = w + (0.05 * np.sin(np.pi * _min_jerk(tau)))[:, None] * np.array([0.0, 1.0])  # slight curve
    el = _elbow(w)
    fore = (w - el) / np.linalg.norm(w - el, axis=1, keepdims=True)
    return resample(np.stack([el, w, w + HAND * fore], 1), L)


def timing_rows() -> list[str]:
    """Same path, different timing. A good alignment removes the difference entirely."""
    ref = arm_reach()
    powers = (0.8, 1.2, 1.4)
    lines = ["## Scenario: timing only", "",
             "Same path, but the clock runs as t^p, so the rep speeds up or slows down partway. "
             "Table shows the mean position error left after alignment, as a fraction of the error "
             "before. 0 = timing fully undone, 1 = no help.", "",
             "| alignment | " + " | ".join(f"p = {p}" for p in powers) + " |", "|---" * (len(powers) + 1) + "|"]
    for mode in MODES:
        base = mode.removesuffix("-refined")
        al = Aligner([ref, ref, ref], mode=base, band_frac=0.2, refine=mode.endswith("-refined"))
        cells = []
        for p in powers:
            bent = arm_reach(p)
            cells.append(f"{np.abs(al.align(bent)[0] - ref).mean() / np.abs(bent - ref).mean():.2f}")
        lines.append(f"| {LABELS[mode]} | " + " | ".join(cells) + " |")
    return lines + [""]


def main() -> None:
    masks = phase_masks([1 / 3, 2 / 3], L)
    names = ("early", "mid", "late")
    lines = ["# Alignment benchmark", "",
             "Generated by `validation/benchmark_alignment.py`. Wrist shift from baseline, in torso lengths, "
             f"mean over {len(SEEDS)} synthetic seeds (20 baseline and 20 test reps each). "
             "Curve error = RMS difference between the reported and the injected shift curve.", ""]
    for scenario, true in truth_curves().items():
        tp = [np.sqrt((true[m] ** 2).mean()) for m in masks]
        rows = {m: [] for m in MODES}
        for seed in SEEDS:
            with tempfile.TemporaryDirectory() as d:
                poses = write_sessions(Path(d), seed=seed, scenario=scenario)
                reps = {k: segment(p)[0] for k, p in poses.items() if k != "practice"}
            for mode in MODES:
                refine = mode.endswith("-refined")
                conds, _, joints = build_conditions(reps, "wrist", L, mode.removesuffix("-refined"), 0.1, 1.0,
                                                    refine=refine)
                c = compare(conds["baseline"], conds["test"], masks, np.random.default_rng(0), 20, 10)
                e = joints.index("wrist")
                curve = c["shift_curve"][:, e]
                rows[mode].append([*c["shift"][:, e], np.sqrt(((curve - true) ** 2).mean()), c["peak_at"][e]])
            print(f"{scenario} seed {seed} done", file=sys.stderr)
        lines += [f"## Scenario: {scenario}", "",
                  "| alignment | " + " | ".join(names) + " | curve error | shift peaks at |",
                  "|---" * (len(names) + 3) + "|",
                  "| injected | " + " | ".join(f"{v:.4f}" for v in tp) + f" | 0 | {np.argmax(true) / (L - 1):.0%} |"]
        for mode in MODES:
            m = np.mean(rows[mode], axis=0)
            lines.append(f"| {LABELS[mode]} | " + " | ".join(f"{v:.4f}" for v in m[:3])
                         + f" | {m[3]:.4f} | {m[4]:.0%} |")
        lines.append("")
    lines += timing_rows()
    out = ROOT / "validation" / "alignment_benchmark.md"
    out.write_text("\n".join(lines))
    print(out.read_text())


if __name__ == "__main__":
    main()
